# Show active git hooks and missing pre-commit installs when entering a repo.
# bash + ble.sh port of https://nedbatchelder.com/blog/202610/making_git_hooks_visible
# As a ble.sh module: save as ~/.local/share/blesh/local/git-hooks.bash
# and put `ble-import git-hooks` in ~/.blerc.
# Or source it from ~/.bashrc after `source ble.sh --noattach`.

# Resolve a possibly-relative path to an absolute one (zsh's ${var:a}).
_git_abspath() {
  local p=$1
  if [[ -d $p ]]; then
    (cd -- "$p" && pwd -P)
  elif [[ $p == /* ]]; then
    printf '%s\n' "$p"
  else
    printf '%s\n' "$PWD/$p"
  fi
}

git_show_hooks() {
  local git_dir
  git_dir=$(git rev-parse --absolute-git-dir 2>/dev/null)
  if [[ -z $git_dir ]]; then
    _git_shown_hooks_dir=
    return
  fi
  local hooks_dir
  hooks_dir=$(_git_abspath "$(git rev-parse --git-path hooks)")
  # Only announce once per repo, not for every cd inside it.
  [[ $hooks_dir == "$_git_shown_hooks_dir" ]] && return
  _git_shown_hooks_dir=$hooks_dir

  local -a hooks=()
  local hook
  for hook in "$hooks_dir"/*; do
    if [[ -f $hook && -x $hook && $hook != *.sample ]]; then
      hooks+=("${hook##*/}")
    fi
  done
  if ((${#hooks[@]})); then
    printf '\e[31mgit hooks:\e[0m %s (from %s)\n' "${hooks[*]}" "$git_dir"
  fi
}

git_check_precommit() {
  local toplevel
  toplevel=$(git rev-parse --show-toplevel 2>/dev/null)
  if [[ -z $toplevel ]]; then
    _git_shown_precommit_dir=
    return
  fi
  # Only announce once per repo, not for every cd inside it.
  [[ $toplevel == "$_git_shown_precommit_dir" ]] && return
  _git_shown_precommit_dir=$toplevel

  [[ -f $toplevel/.pre-commit-config.yaml ]] || return

  local hooks_dir pc_tool=
  hooks_dir=$(_git_abspath "$(git rev-parse --git-path hooks)")
  if [[ -f $hooks_dir/pre-commit ]]; then
    if grep -q 'File generated by prek:' "$hooks_dir/pre-commit" 2>/dev/null; then
      pc_tool=prek
    elif grep -q 'File generated by pre-commit:' "$hooks_dir/pre-commit" 2>/dev/null; then
      pc_tool=pre-commit
    fi
  fi
  if [[ -n $pc_tool ]]; then
    echo "$pc_tool installed"
  else
    printf '\e[31mpre-commit:\e[0m not installed, %s (%s)\n' \
      "run 'pre-commit install' or 'prek install'" \
      "$toplevel/.pre-commit-config.yaml"
  fi
}

if [[ ${BLE_VERSION-} ]]; then
  # != adds the handler only if it isn't registered yet, so re-sourcing is safe.
  blehook CHPWD!=git_show_hooks
  blehook CHPWD!=git_check_precommit
fi

# CHPWD doesn't fire for the starting directory, so check it once now.
git_show_hooks
git_check_precommit